import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const menuJson = JSON.parse(readFileSync(join(root, "public", "menu.json"), "utf8"))

const esc = (s) => String(s).replace(/'/g, "''")
const str = (s) => (s == null || s === "" ? "NULL" : `'${esc(s)}'`)

const out = []
out.push("-- ===========================================================================")
out.push("-- Stories Resto Cafe — menu seed data (generated from public/menu.json)")
out.push("-- Generated by scripts/export-menu-to-sql.mjs — re-run that script to refresh.")
out.push("-- ===========================================================================")
out.push("")
out.push("-- Categories")
for (let i = 0; i < menuJson.categories.length; i++) {
  const c = menuJson.categories[i]
  out.push(
    `insert into public.categories (id, label_en, label_ar, sort_order) values (${str(c.id)}, ${str(c.label.en)}, ${str(c.label.ar)}, ${i});`,
  )
}
out.push("")
out.push("-- Menu items")
for (const m of menuJson.menu) {
  const modifiers = JSON.stringify(m.modifiers ?? [])
  out.push(
    `insert into public.menu (id, category, title_en, title_ar, description_en, description_ar, price, image, tag_en, tag_ar, modifiers) values (` +
      `${str(m.id)}, ${str(m.category)}, ${str(m.title.en)}, ${str(m.title.ar)}, ${str(m.description.en)}, ${str(m.description.ar)}, ` +
      `${m.price}, ${str(m.image)}, ${str(m.tag?.en)}, ${str(m.tag?.ar)}, '${esc(modifiers)}'::jsonb);`,
  )
}
out.push("")

writeFileSync(join(root, "supabase", "menu-seed.sql"), out.join("\n"), "utf8")
console.log(`Wrote supabase/menu-seed.sql (${menuJson.categories.length} categories, ${menuJson.menu.length} items)`)
